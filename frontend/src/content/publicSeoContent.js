export function normalizePublicPath(path = "/") {
  if (!path) return "/";
  if (path.length > 1 && path.endsWith("/")) {
    return path.slice(0, -1);
  }
  return path;
}

export function getPublicSeoContent(path = "/") {
  return PUBLIC_SEO_CONTENT[normalizePublicPath(path)] || null;
}
